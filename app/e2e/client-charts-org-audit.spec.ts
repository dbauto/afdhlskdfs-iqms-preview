import { expect, test } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.goto("/")
  await page.evaluate(() => localStorage.setItem("iqms.viewAs", "p-al"))
})

test("existing charts show each bar's value on hover and have labelled axes", async ({ page }) => {
  await page.goto("/qms/objectives/OBJ-2026-03")
  const bar = page.getByRole("img", { name: /^August 2026: 91\.8%, below target$/ })
  await bar.hover()
  await expect(page.getByRole("tooltip")).toContainText("Target ≥ 94%")
  await page.goto("/qms/objectives")
  await bar.focus()
  await expect(page.getByRole("tooltip")).toContainText("August 2026")
  await page.goto("/")
  const gap = page.getByRole("img", { name: /^Clause 4, missing: \d+%$/ }).first()
  await gap.hover()
  await expect(page.getByRole("tooltip")).toContainText("Clause 4 · Missing")
})

test("org chart: add, rename, edit and delete straight on the chart", async ({ page }) => {
  await page.goto("/qms/organization?tab=chart")
  await expect(page.getByRole("button", { name: "Add box" })).toHaveCount(0)
  await page.getByRole("button", { name: /^Operations, Department/ }).click()
  const bar = page.getByRole("toolbar", { name: "Actions for Operations" })
  await bar.getByRole("button", { name: "Add under" }).click()
  const add = page.getByRole("dialog", { name: "Add a box" })
  await add.getByRole("button", { name: "Add box" }).click()
  await expect(add.getByText("Give the box a name")).toBeVisible()
  await add.getByLabel("Name").fill("Tool room")
  await add.getByRole("button", { name: "Add box" }).click()
  await expect(page.getByRole("button", { name: /^Tool room, Department/ })).toBeVisible()
  // the + under a box opens the same window
  await page.getByRole("button", { name: /^Quality, Department/ }).hover()
  await page.getByRole("button", { name: "Add a box under Quality" }).click()
  await expect(page.getByRole("dialog", { name: "Add a box" })).toBeVisible()
  await page.getByRole("dialog", { name: "Add a box" }).getByRole("button", { name: "Cancel" }).click()
  await page.getByRole("button", { name: /^Tool room, Department/ }).click()

  await page.getByRole("toolbar", { name: "Actions for Tool room" }).getByRole("button", { name: "Edit" }).click()
  const win = page.getByRole("dialog", { name: "Edit Tool room" })
  await win.getByLabel("Kind").selectOption("Team")
  await win.getByLabel("Responsibilities").fill("Makes and repairs jigs")
  await page.keyboard.press("Escape")
  await expect(page.getByRole("button", { name: /^Tool room, Team/ })).toBeVisible()

  await page.getByRole("button", { name: /^Tool room, Team/ }).dblclick()
  await page.getByLabel("Rename Tool room").fill("Tooling")
  await page.getByLabel("Rename Tool room").press("Enter")
  await expect(page.getByRole("button", { name: /^Tooling, Team/ })).toBeVisible()

  await page.getByRole("button", { name: /^Tooling, Team/ }).click()
  await page.getByRole("toolbar", { name: "Actions for Tooling" }).getByRole("button", { name: "Delete" }).click()
  await page.getByRole("dialog", { name: "Delete Tooling?" }).getByRole("button", { name: "Delete box" }).click()
  await expect(page.getByRole("button", { name: /^Tooling, Team/ })).toHaveCount(0)
})

test("profile has no What we do, process covers are gone, and how a process works is described and linked", async ({ page }) => {
  await page.goto("/qms/organization?tab=profile")
  await expect(page.getByText("What we do")).toHaveCount(0)

  await page.goto("/qms/processes/operations")
  await expect(page.getByRole("button", { name: "Change cover" })).toHaveCount(0)
  const inputs = page.getByRole("region", { name: "Inputs" })
  await inputs.getByLabel("Inputs description").fill("Accepted orders from Sales\nReleased drawings")
  await inputs.getByLabel("Inputs description").blur()
  await inputs.getByRole("button", { name: /Link input/ }).click()
  const picker = page.getByRole("dialog", { name: "Choose what to link" })
  await picker.getByRole("checkbox").first().click()
  await picker.getByRole("button", { name: "Link 1" }).click()
  await expect(inputs.getByText("Linked")).toBeVisible()
  await page.reload()
  await expect(page.getByRole("region", { name: "Inputs" }).getByLabel("Inputs description")).toHaveValue("Accepted orders from Sales\nReleased drawings")
})

test("new audit plan: internal by frequency creates a series; external lists the mock and certification audits; templates and blank", async ({ page }) => {
  await page.goto("/audits?tab=plans")
  await page.getByRole("tab", { name: /Audit plans/ }).click()
  await page.getByRole("button", { name: "New audit plan" }).click()
  const dlg = page.getByRole("dialog", { name: "New audit plan" })
  await expect(dlg.getByRole("radio", { name: /Internal audit/ })).toHaveAttribute("aria-checked", "true")
  await dlg.getByRole("radio", { name: /Quarterly/ }).click()
  await dlg.getByLabel("First audit").fill("2027-01-15")
  await expect(dlg.getByText("Creates 4 audit plans")).toBeVisible()
  await dlg.getByRole("button", { name: "Create 4 plans" }).click()
  await expect(page.getByRole("heading", { name: "Internal audit, Q1 2027" })).toBeVisible()
  await expect(page.getByText("Internal · Quarterly · 1 of 4")).toBeVisible()

  await page.getByRole("button", { name: "Save as template" }).click()
  await expect(page.getByText("Saved as a template")).toBeVisible()

  await page.goto("/audits")
  await page.getByRole("tab", { name: /Audit plans/ }).click()
  await page.getByRole("button", { name: /^Internal/ }).click()
  await expect(page.getByText("Internal · Quarterly · 4 of 4")).toBeVisible()
  await page.getByRole("button", { name: "New audit plan" }).click()
  await dlg.getByRole("radio", { name: /External audit/ }).click()
  for (const k of ["Mock audit", "Stage 1", "Stage 2", "Surveillance", "Recertification"]) await expect(dlg.getByRole("radio", { name: new RegExp(`^${k}`) })).toBeVisible()
  await dlg.getByRole("radio", { name: /^Blank/ }).click()
  await dlg.getByLabel("Date").fill("2027-03-01")
  await dlg.getByLabel("Auditor 1 name").fill("Auditor A")
  await dlg.getByRole("button", { name: "Create plan" }).click()
  await expect(page.getByText(/External · Stage 2/)).toBeVisible()
})

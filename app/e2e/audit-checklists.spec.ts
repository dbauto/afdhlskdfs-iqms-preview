import { test, expect } from '@playwright/test'
test('3a: opening does not save; real edits persist; released versions stay unchanged', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => { localStorage.setItem('iqms.viewAs', 'p-dr') })
  await page.goto('/audits/IA-2026-10/checklist')
  await expect(page.getByText('Unsaved draft', { exact: false }).first()).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('thryvems.preview.v1')!).state.auditChecklists.some((c: any) => c.auditId === 'IA-2026-10'))).toBe(false)
  await page.getByRole('button', { name: 'Add question', exact: true }).click()
  await page.locator('#q-text').fill('How is competence reviewed?')
  await page.locator('#q-respond').selectOption('Both')
  await page.locator('#q-evidence-rule').selectOption('Required')
  await page.locator('#q-type').selectOption('Multiple choice')
  await page.locator('#q-choices').fill('Training review\nObserved performance')
  await page.getByRole('switch', { name: 'Use pre-audit questionnaire' }).click()
  await page.reload()
  await page.getByRole('button', { name: /How is competence reviewed/ }).click()
  await expect(page.locator('#q-text')).toHaveValue('How is competence reviewed?')
  await expect(page.locator('#q-choices')).toHaveValue('Training review\nObserved performance')
  await page.getByRole('button', { name: 'Mark checklist ready', exact: true }).click()
  await expect(page).toHaveURL(/\/audits\/IA-2026-10$/)
  await page.goto('/audits/IA-2026-10/checklist')
  const released = await page.evaluate(() => JSON.parse(localStorage.getItem('thryvems.preview.v1')!).state.auditChecklists.find((c: any) => c.auditId === 'IA-2026-10' && c.version === 1))
  await expect(page.locator('#q-text')).toBeDisabled()
  await page.getByRole('button', { name: 'Start checklist revision', exact: true }).click()
  await page.locator('#revision-reason').fill('Add a question for this cycle')
  await page.getByRole('button', { name: 'Create revision draft', exact: true }).click()
  await page.getByRole('button', { name: /How is competence reviewed/ }).click()
  await page.locator('#q-text').fill('Revised question')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('thryvems.preview.v1')!).state.auditChecklists.find((c: any) => c.auditId === 'IA-2026-10' && c.version === 1))).toEqual(released)
  await page.screenshot({ path: '../../deliverables/audit-3a-builder.png', fullPage: true })
})

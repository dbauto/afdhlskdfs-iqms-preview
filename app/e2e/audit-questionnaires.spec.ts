import { openPageLink } from "./helpers/page-links"
import { test, expect, type Page } from "@playwright/test"
test.setTimeout(90_000)
async function as(page: Page, id: string) {
  await page.evaluate((id) => localStorage.setItem("iqms.viewAs", id), id)
  await page.reload()
}
test("3b: assignment, own draft recovery, required evidence, submission and controlled clarification", async ({ page }) => {
  await page.goto("/")
  await as(page, "p-dr")
  await page.goto("/audits/IA-2026-10/checklist")
  await page.getByRole("button", { name: "Add question", exact: true }).click()
  await page.locator('textarea[id^="q-text-"]').last().fill("How do you check competence?")
  await page.getByRole("button", { name: /Question \d+ settings/ }).last().click()
  await page.locator("#q-respond").selectOption("Both")
  await page.locator("#q-type").selectOption("Yes / No / N/A")
  await page.locator("#q-evidence-rule").selectOption("Required")
  await page.getByRole("button", { name: "Done", exact: true }).click()
  await page.getByRole("switch", { name: "Use pre-audit questionnaire" }).click()
  await page.getByRole("button", { name: "Mark checklist ready" }).click()
  await page.goto("/audits/IA-2026-10/questionnaires")
  await page.locator("#qa-person").selectOption("Joy Aquino")
  await page.getByRole("button", { name: "Assign questionnaire", exact: true }).click()
  page = await openPageLink(page, page.getByRole("link", { name: /AQA-0001/ }))
  const url = page.url()
  await as(page, "p-ja")
  await expect(page.getByRole("heading", { name: "Auditee questionnaire" })).toBeVisible()
  await page.getByRole("radio", { name: "Yes", exact: true }).check()
  await page.locator("#aq-explanation").fill("We review competence each quarter.")
  await page.reload()
  await expect(page.locator("#aq-explanation")).toHaveValue("We review competence each quarter.")
  await page.getByRole("button", { name: "Submit questionnaire", exact: true }).click()
  await page.getByRole("button", { name: "Confirm submission" }).click()
  await expect(page.getByRole("dialog").getByRole("alert")).toContainText("Link the required supporting evidence")
  await page.getByRole("button", { name: "Keep working" }).click()
  await page.getByRole("textbox", { name: "Evidence URL", exact: true }).fill("http://bad.example/evidence")
  await page.getByRole("button", { name: "Add evidence link" }).click()
  await expect(page.getByRole("alert").filter({ hasText: "Use a full https://" })).toBeVisible()
  await page.getByRole("textbox", { name: "Evidence URL", exact: true }).fill("https://example.com/competence")
  await page.getByRole("textbox", { name: "Evidence title", exact: true }).fill("Competence records")
  await page.getByRole("button", { name: "Add evidence link" }).click()
  await page.getByRole("button", { name: "Submit questionnaire", exact: true }).click()
  await page.getByRole("button", { name: "Confirm submission" }).click()
  await expect(page.getByRole("radio", { name: "Yes", exact: true })).toBeDisabled()
  await as(page, "p-bc")
  await expect(page.getByText("This page or record doesn’t exist")).toBeVisible()
  await as(page, "p-dr")
  await page.goto(url)
  await page.getByRole("textbox", { name: "Clarification request", exact: true }).fill("Which quarter did you review?")
  await page.getByRole("button", { name: "Send request", exact: true }).click()
  await as(page, "p-ja")
  await page.locator("#aq-explanation").fill("The third quarter review is linked.")
  await page.getByRole("textbox", { name: "Reply to ACR-0001" }).fill("Q3 2026")
  await page.getByRole("button", { name: "Send clarification reply" }).click()
  await page.getByRole("button", { name: "Submit questionnaire", exact: true }).click()
  await page.getByRole("button", { name: "Confirm submission" }).click()
  await expect(page.getByText("Resubmitted", { exact: true }).first()).toBeVisible()
  await page.screenshot({ path: "../../deliverables/audit-3b-questionnaire.png", fullPage: true })
  await as(page, "p-dr")
  await page.getByRole("button", { name: "Resolve clarification ACR-0001" }).click()
  const counts = await page.evaluate(() => {
    const s = JSON.parse(localStorage.getItem("thryvems.preview.v1")!).state
    return {
      assignments: s.questionnaireAssignments.length,
      responses: s.auditeeResponses.length,
      history: s.auditeeResponses[0].history.length,
      submissions: s.notifications.filter((n: any) => n.title.includes("AQA-0001 submitted")).length,
    }
  })
  expect(counts.assignments).toBe(1)
  expect(counts.responses).toBe(1)
  expect(counts.history).toBeGreaterThan(0)
  expect(counts.submissions).toBe(1)
})

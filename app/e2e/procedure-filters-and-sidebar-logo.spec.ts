import { test, expect } from "@playwright/test"

test("procedure filters sit beside search and the chevron opens the searchable options", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto("/qms/procedures")
  const search = page.getByPlaceholder("Filter by number, title or owner")
  const process = page.getByRole("combobox", { name: "Process" })
  const type = page.getByRole("combobox", { name: "Type" })
  await expect(search).toBeVisible()
  await expect(process).toBeVisible()
  await expect(type).toBeVisible()

  const positions = await Promise.all([search.locator(".."), process, type].map((control) => control.boundingBox()))
  expect(positions.every(Boolean)).toBeTruthy()
  expect(Math.abs(positions[0]!.y - positions[1]!.y)).toBeLessThan(5)
  expect(Math.abs(positions[0]!.y - positions[2]!.y)).toBeLessThan(5)
  expect(positions[0]!.x).toBeLessThan(positions[1]!.x)
  expect(positions[1]!.x).toBeLessThan(positions[2]!.x)

  const trigger = process.locator("..").getByRole("button", { name: "Search dropdown options" })
  await expect(trigger.locator("svg.lucide-chevron-down")).toBeVisible()
  await trigger.click()
  const optionSearch = page.getByRole("textbox", { name: "Search options" })
  await expect(optionSearch).toBeFocused()
  await optionSearch.fill("operations")
  await page.getByRole("listbox", { name: "Matching options" }).getByRole("option", { name: "Operations" }).click()
  await expect(process).toHaveValue("Operations")
  await expect(optionSearch).toHaveCount(0)
})

test("collapsed sidebar product logo is 20 percent smaller without changing sidebar width", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto("/qms/procedures")
  const sidebar = page.getByRole("navigation", { name: "Main" })
  const collapse = page.getByRole("button", { name: "Collapse sidebar" })
  if (await collapse.isVisible()) await collapse.click()
  await expect(page.getByRole("button", { name: "Expand sidebar" })).toBeVisible()
  const logo = sidebar.getByRole("link", { name: "ThryveMS overview" }).locator("img:visible").first()
  await expect(logo).toBeVisible()
  const bounds = await logo.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.height).toBeCloseTo(25.6, 0)
  expect(await sidebar.evaluate((node) => node.getBoundingClientRect().width)).toBeCloseTo(72, 0)
})

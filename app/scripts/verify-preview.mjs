import { chromium, expect } from '@playwright/test'
import { createServer } from 'node:http'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import assert from 'node:assert/strict'
const html = await readFile('dist/index.html')
const server = createServer((req, res) => { if (req.url.split('?')[0] !== '/afdhlskdfs-iqms-preview/') { res.writeHead(404); return res.end() }; res.setHeader('Content-Type', 'text/html'); res.end(html) })
await new Promise(r => server.listen(4175, '127.0.0.1', r))
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined })
try {
  for (const base of ['http://127.0.0.1:4175/afdhlskdfs-iqms-preview/', pathToFileURL(resolve('dist/index.html')).href]) {
    const context = await browser.newContext()
    const page = await context.newPage()
    const errors = []
    context.on('page', p => p.on('pageerror', e => errors.push(e.message)))
    context.on('request', r => { if (!r.url().startsWith(base.split('#')[0]) && !r.url().startsWith('data:')) errors.push(`External dependency: ${r.url()}`) })
    await page.goto(base + '#/qms/objectives/OBJ-2026-01')
    await page.locator('h1').waitFor()
    assert.ok(!(await page.textContent('body')).includes('This page or record doesn’t exist'))
    await page.goto(base + '#/audits/templates/CT-02?mode=view')
    await page.getByRole('heading', { name: 'Purchasing & suppliers', exact: true }).waitFor()
    await expect(page.locator('textarea[id^="q-text-"]').first()).toHaveAttribute('readonly', '')
    await page.getByRole('button', { name: 'Edit questions', exact: true }).click()
    await expect(page.locator('textarea[id^="q-text-"]').first()).toBeEditable()
    await page.getByRole('button', { name: 'Question 1 settings', exact: true }).click()
    await page.getByRole('heading', { name: 'Question settings', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await page.goto(base + '#/audits/IA-2026-05/checklist?version=IA-2026-05&mode=view')
    await page.getByRole('heading', { name: 'Checklist for the Operations audit', exact: true }).waitFor()
    assert.ok(await page.locator('textarea[id^="q-text-"]').count() > 1)
    await expect(page.locator('textarea[id^="q-text-"]').first()).toHaveAttribute('readonly', '')
    await page.getByRole('button', { name: 'Edit draft', exact: true }).click()
    await expect(page.locator('textarea[id^="q-text-"]').first()).toBeEditable()
    await page.goto(base + '#/management-review/MR-2026-02')
    await page.getByRole('button', { name: /Quality objectives/ }).click()
    const link = page.locator('a[aria-label^="Open OBJ-2026-01"]').first()
    const [popup] = await Promise.all([context.waitForEvent('page'), link.click()])
    await popup.locator('h1').waitFor()
    assert.ok(popup.url().endsWith('#/qms/objectives/OBJ-2026-01'))
    await page.goto(base + '#/qms/organization')
    await page.getByRole('button', { name: 'Revise scope', exact: true }).click()
    await page.locator('#scope-statement').fill('Synthetic scope revised through the single-file preview.')
    await page.locator('#rv-note').fill('Verify scope editing in the single-file preview.')
    await page.getByRole('button', { name: 'Start revision 08', exact: true }).click()
    await page.reload()
    assert.ok((await page.textContent('body')).includes('Synthetic scope revised through the single-file preview.'))
    await page.goto(base + '#/documents/QMS-MAN-001')
    await page.getByRole('button', { name: 'Share', exact: true }).click()
    await page.getByRole('radio', { name: 'Can comment', exact: true }).click()
    assert.equal(await page.getByRole('radio', { name: 'Can comment', exact: true }).getAttribute('aria-checked'), 'true')
    await page.getByRole('dialog').getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'View more revision updates', exact: true }).click()
    assert.ok(await page.getByRole('dialog', { name: 'Revision history' }).isVisible())
    await page.getByRole('dialog').getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'Suspend effectivity', exact: true }).click()
    await page.locator('#effectivity-reason').fill('Synthetic single-file effectivity test.')
    await page.getByRole('dialog').getByRole('button', { name: 'Suspend effectivity', exact: true }).click()
    await page.reload()
    assert.ok((await page.textContent('body')).includes('Effectivity suspended'))
    assert.deepEqual(errors, [])
    console.log(`PASS single HTML, no external dependencies, deep link/new tab, saved scope, share, history and effectivity: ${base.startsWith('file:') ? 'disk' : 'Pages subpath'}`)
    await context.close()
  }
} finally { await browser.close(); await new Promise(r => server.close(r)) }
